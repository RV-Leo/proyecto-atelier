-- Modulo: diseno generativo (README: "Crear imagenes de prendas a partir de
-- detalles como el tipo, el estilo, los colores y la tela").

CREATE TABLE prenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    tipo_prenda VARCHAR(40) NOT NULL,
    estilo VARCHAR(40) NOT NULL,
    colores VARCHAR(200),
    tela VARCHAR(80),
    descripcion TEXT,
    prompt_ia TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'borrador',
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_prenda_estado
        CHECK (estado IN ('borrador', 'generando', 'generada', 'analizada'))
);

-- Cada prenda puede tener varias propuestas de imagen (Qwen-Image crea
-- "distintas propuestas de la prenda" segun el README).
CREATE TABLE propuesta_diseno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prenda_id BIGINT NOT NULL REFERENCES prenda (id) ON DELETE CASCADE,
    imagen_url VARCHAR(500) NOT NULL,
    prompt_usado TEXT,
    seleccionada BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX ix_propuesta_diseno_prenda ON propuesta_diseno (prenda_id);
