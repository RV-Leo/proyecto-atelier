-- Modulo: tendencias (README: "Consultar tendencias de Europa y America a
-- partir de Pinterest y tiendas de marca").

CREATE TABLE tendencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    region VARCHAR(20) NOT NULL,
    fuente VARCHAR(30) NOT NULL,
    url_origen VARCHAR(500) NOT NULL,
    imagen_url VARCHAR(500),
    colores VARCHAR(200),
    estilo VARCHAR(40),
    tela VARCHAR(80),
    capturado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_tendencia_region
        CHECK (region IN ('europa', 'america', 'global')),
    CONSTRAINT ck_tendencia_fuente
        CHECK (fuente IN ('pinterest', 'tienda_marca', 'otro')),
    CONSTRAINT uq_tendencia_url UNIQUE (url_origen)
);

CREATE INDEX ix_tendencia_region ON tendencia (region);
CREATE INDEX ix_tendencia_capturado ON tendencia (capturado_en DESC);
