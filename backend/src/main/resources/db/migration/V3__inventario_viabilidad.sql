-- Modulos: viabilidad e inventario (README: "Revisar si hay materiales para
-- producir una prenda y buscar alternativas cuando falte stock").

CREATE TABLE material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    color VARCHAR(50),
    unidad VARCHAR(20) NOT NULL,
    stock NUMERIC(12, 3) NOT NULL DEFAULT 0,
    stock_minimo NUMERIC(12, 3) NOT NULL DEFAULT 0,
    proveedor VARCHAR(120),
    precio_unitario NUMERIC(12, 2),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_material_unidad
        CHECK (unidad IN ('metro', 'unidad', 'kilogramo', 'rollo')),
    CONSTRAINT ck_material_stock CHECK (stock >= 0),
    CONSTRAINT ck_material_stock_minimo CHECK (stock_minimo >= 0)
);

CREATE INDEX ix_material_activo ON material (activo);

-- Que materiales, y en cuanta cantidad, necesita cada prenda para producirse.
CREATE TABLE prenda_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prenda_id BIGINT NOT NULL REFERENCES prenda (id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES material (id) ON DELETE RESTRICT,
    cantidad_requerida NUMERIC(12, 3) NOT NULL,
    CONSTRAINT uq_prenda_material UNIQUE (prenda_id, material_id),
    CONSTRAINT ck_prenda_material_cantidad CHECK (cantidad_requerida > 0)
);

CREATE INDEX ix_prenda_material_material ON prenda_material (material_id);

-- Resultado de comparar una idea con el stock real.
CREATE TABLE analisis_viabilidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prenda_id BIGINT NOT NULL REFERENCES prenda (id) ON DELETE CASCADE,
    viable BOOLEAN NOT NULL,
    puntaje INTEGER,
    comentario TEXT,
    analizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_analisis_puntaje
        CHECK (puntaje IS NULL OR puntaje BETWEEN 0 AND 100)
);

CREATE INDEX ix_analisis_viabilidad_prenda ON analisis_viabilidad (prenda_id);

-- Alternativas sugeridas cuando falta stock de un material.
CREATE TABLE alternativa_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analisis_id BIGINT NOT NULL
        REFERENCES analisis_viabilidad (id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES material (id) ON DELETE CASCADE,
    material_alternativo_id BIGINT NOT NULL
        REFERENCES material (id) ON DELETE RESTRICT,
    motivo VARCHAR(200) NOT NULL,
    cantidad_sugerida NUMERIC(12, 3),
    CONSTRAINT ck_alternativa_distinto
        CHECK (material_id <> material_alternativo_id)
);

CREATE INDEX ix_alternativa_stock_analisis ON alternativa_stock (analisis_id);
CREATE INDEX ix_alternativa_stock_material ON alternativa_stock (material_id);
